#!/usr/bin/env python3
"""Evidence manifest: every %SRC tag in the paper -> file, exists?, SHA-256, line of the paper it backs."""
import re, os, hashlib, glob
ROOT=os.path.abspath(os.path.join(os.path.dirname(__file__),'..'))
def sha(p):
    h=hashlib.sha256()
    with open(p,'rb') as f:
        for b in iter(lambda:f.read(1<<20),b''): h.update(b)
    return h.hexdigest()
rows=[]; cache={}
for t in sorted(glob.glob(os.path.join(ROOT,'06_PAPER','*.tex'))+glob.glob(os.path.join(ROOT,'06_PAPER','figs','*.tex'))):
    for n,line in enumerate(open(t,encoding='utf-8',errors='replace'),1):
        for m in re.finditer(r'%\s*SRC:\s*(.+)$',line):
            txt=m.group(1).strip()
            paths=re.findall(r'((?:0[0-9]_[A-Z_]+|04_WORK|05_RESULTS|06_PAPER|08_GEM5|tools)/[^\s,;()]+)',txt)
            if not paths: rows.append((os.path.relpath(t,ROOT),n,txt[:90],'(no file path)','','')); continue
            for p in paths:
                p=p.rstrip('.:');full=os.path.join(ROOT,p)
                g=glob.glob(full)
                if g and os.path.isfile(g[0]):
                    if g[0] not in cache: cache[g[0]]=sha(g[0])
                    st,h='OK',cache[g[0]][:16]
                elif g: st,h='DIR',''
                else: st,h='MISSING',''
                rows.append((os.path.relpath(t,ROOT),n,txt[:90],p,st,h))
out=os.path.join(ROOT,'05_RESULTS','EVIDENCE_MANIFEST.md')
with open(out,'w') as f:
    f.write('# WEPWAWET-CORE evidence manifest\n\nEvery %SRC tag in 06_PAPER mapped to the file that backs it, with SHA-256 (first 16 hex). Generated by tools/evidence_manifest.py.\n\n')
    f.write('| paper file:line | backing file | status | sha256 | tag text |\n|---|---|---|---|---|\n')
    for r in rows: f.write(f'| {r[0]}:{r[1]} | {r[3]} | {r[4]} | {r[5]} | {r[2].replace("|","/")} |\n')
from collections import Counter
c=Counter(r[4] or 'NOPATH' for r in rows); print(len(rows),'tags',dict(c)); print(out)
for r in rows:
    if r[4]=='MISSING' or r[3]=='(no file path)': print('CHECK', r[0], r[1], r[2][:70])
