#!/usr/bin/env python3
"""Build Fig. (attitude jitter box plot, B/W) and the mission results table from collected runs.
usage: python3 tools/make_mission_fig.py RUNS_DIR [--tag-filter SUBSTR]
RUNS_DIR = 05_RESULTS/board_logs/aup1/wepwawet-core/logs/mission_runs (after `.\\wcore.ps1 collect`)
Writes figs/fig_mission.pdf and tab_mission.tex. Every number comes from the run folders; nothing is typed in."""
import csv, glob, json, os, statistics, sys
import matplotlib; matplotlib.use('Agg')
import matplotlib.pyplot as plt
plt.rcParams.update({'font.family': 'serif', 'font.serif': ['Times', 'Nimbus Roman', 'DejaVu Serif'], 'font.size': 8,
                     'axes.linewidth': 0.6, 'lines.linewidth': 0.8, 'pdf.fonttype': 42})
runs_dir = sys.argv[1]; filt = sys.argv[3] if len(sys.argv) > 3 and sys.argv[2] == '--tag-filter' else None
def jl(p):
    try: return json.load(open(p))
    except Exception: return None
def cfg(P):
    if P.get('rate', 0) == 0: return 'No signing'
    b = 'Fabric' if P['backend'] == 'fpga' else 'Neon'
    if P['backend'] == 'cpu' and int(P.get('signer_prio', 0)) > 0: b += ' RT'
    if P.get('pinning') == 'none': b += ' unpinned'
    return b
groups = {}
for d in sorted(glob.glob(os.path.join(runs_dir, '*'))):
    P = jl(os.path.join(d, 'params.json'))
    if not P or (filt and filt not in d): continue
    S = jl(os.path.join(d, 'run_summary.json')) or {}
    A = jl(os.path.join(d, 'adcs.json')) or {}; Y = jl(os.path.join(d, 'payload.json')) or {}
    jit = []
    try:
        with open(os.path.join(d, 'adcs.csv')) as fh:
            for r in csv.DictReader(fh): jit.append(float(r['jitter_us']))
    except Exception: pass
    g = groups.setdefault(cfg(P), {'jit': [], 'runs': []})
    g['jit'] += jit; g['runs'].append({'dir': os.path.basename(d), 'adcs': A, 'pay': Y, 'sum': S})
order = [k for k in ['No signing', 'Fabric', 'Neon', 'Neon RT', 'Fabric unpinned', 'Neon unpinned'] if k in groups] + sorted(k for k in groups if k not in ['No signing', 'Fabric', 'Neon', 'Neon RT', 'Fabric unpinned', 'Neon unpinned'])
if not order: raise SystemExit('no runs found in ' + runs_dir)
fig, ax = plt.subplots(figsize=(3.5, 2.0))
data = [[max(x, 1.0) for x in groups[k]['jit']] or [1.0] for k in order]
ax.boxplot(data, whis=(1, 99), showfliers=False, medianprops={'color': 'black'}, boxprops={'color': 'black'},
           whiskerprops={'color': 'black'}, capprops={'color': 'black'})
for i, k in enumerate(order, 1):
    if groups[k]['jit']: ax.plot(i, max(groups[k]['jit']), marker='x', color='black', ms=4)
ax.set_yscale('log'); ax.set_ylabel('Release jitter ($\\mu$s)')
ax.set_xticks(range(1, len(order) + 1)); ax.set_xticklabels(order, rotation=30, ha='right', fontsize=7)
ax.grid(axis='y', linewidth=0.3, color='0.8'); fig.tight_layout()
os.makedirs('figs', exist_ok=True); fig.savefig('figs/fig_mission.pdf'); 
def pct(v, q):
    v = sorted(v); return v[min(len(v) - 1, int(q * (len(v) - 1) + 0.5))] if v else float('nan')
rows = []
for k in order:
    g = groups[k]; R = g['runs']
    misses = sum((r['adcs'].get('deadline_misses') or 0) for r in R)
    pm = [r['pay'].get('miss_rate') for r in R if r['pay'].get('miss_rate') is not None]
    lat = [r['sum'].get('sign', {}).get('lat_ms_p50') for r in R]; lat = [x for x in lat if x is not None]
    lat99 = [r['sum'].get('sign', {}).get('lat_ms_p99') for r in R]; lat99 = [x for x in lat99 if x is not None]
    ok = sum((r['sum'].get('sign', {}).get('ok') or 0) for r in R); req = sum((r['sum'].get('sign', {}).get('requested') or 0) for r in R)
    j = g['jit']
    rows.append(f"{k} & {len(R)} & {pct(j,.5):.0f} & {pct(j,.99):.0f} & {max(j) if j else float('nan'):.0f} & {misses} & "
                f"{100*statistics.mean(pm) if pm else float('nan'):.1f} (sd {100*statistics.pstdev(pm) if len(pm)>1 else 0:.1f}) & "
                f"{statistics.median(lat) if lat else float('nan'):.2f} / {max(lat99) if lat99 else float('nan'):.1f} & {ok}/{req}\\\\")
with open('tab_mission.tex', 'w') as fh:
    fh.write("% generated by tools/make_mission_fig.py from " + runs_dir + "\n")
    fh.write("\\begin{table}[t]\\caption{Mission timing by signing configuration}\\label{tab:mission}\\centering\\scriptsize\\setlength{\\tabcolsep}{2pt}\n")
    fh.write("\\begin{tabular}{lrrrrrrrr}\\toprule\nConfiguration & Runs & \\multicolumn{3}{c}{Attitude jitter ($\\mu$s)} & Att. & Payload & Sign (ms) & Cmds\\\\\n"
             " & & median & 99th & worst & misses & misses (\\%) & median / 99th & accepted\\\\\\midrule\n")
    fh.write("\n".join(rows) + "\n\\bottomrule\\end{tabular}\\end{table}\n")
print('wrote figs/fig_mission.pdf and tab_mission.tex for', order)
