#!/usr/bin/env python3
"""Mission table from 05_RESULTS/final_analysis/final_runs.csv (AUP1 rows, loaded runs). Writes tab_mission.tex."""
import csv
R=[r for r in csv.DictReader(open('../05_RESULTS/final_analysis/final_runs.csv')) if r['host']=='aup1' and r['tag'] in ('f1','f2','f3','fbase1','fbase2','fbase3')]
names=[('nocrypto','No signing'),('fpga','Fabric'),('fpga_unpinned','Fabric, unpinned'),('cpu','Neon'),('cpu_rt70','Neon, RT 70'),('cpu_unpinned','Neon, unpinned')]
f=lambda x: float(x) if x not in ('','-','nan') else None
rows=[]
for k,lab in names:
    G=[r for r in R if r['cfg']==k]
    if not G: continue
    sg=[int(r['signed']) for r in G]; med=[f(r['sign_med_ms']) for r in G if f(r['sign_med_ms'])]; p99=[f(r['sign_p99_ms']) for r in G if f(r['sign_p99_ms'])]
    stall=[f(r['adcs_jit_max_ms']) for r in G]; nst=[int(r['adcs_stalls_gt100ms']) for r in G]; wall=[f(r['pay_wall_s']) for r in G]
    cr=sum(r['crashed']=='True' for r in G)
    sgs='--' if k=='nocrypto' else '/'.join(str(s) for s in sg)
    ms="--" if not med else (f"{min(med):.2f}" if f"{min(med):.2f}"==f"{max(med):.2f}" else f"{min(med):.2f}--{max(med):.2f}")
    p9='--' if not p99 else f"{min(p99):.1f}--{max(p99):.1f}"
    rows.append(f"{lab} & {len(G)} & {sgs} & {ms} & {p9} & {max(stall)/1e3:.1f} & {sum(nst)} & {min(wall):.1f}--{max(wall):.1f} & {cr}\\\\")
with open('tab_mission.tex','w') as fh:
    fh.write("% generated by tools/mission_table.py from 05_RESULTS/final_analysis/final_runs.csv (AUP1, tags f1-f3, fbase1-3)\n")
    fh.write("\\begin{table*}[t]\\caption{Node 1 under the imaging-pass workload, 10 signed commands per second, three 60~s runs per configuration}\\label{tab:mission}\\centering\\footnotesize\n")
    fh.write("\\begin{tabular}{lrcccrrcc}\\toprule\nConfiguration & Runs & Signed (of 600) & Sign median (ms) & Sign 99th (ms) & Worst attitude stall (s) & Stalls $>$0.1 s & Payload wall time (s) & F$'$ aborts\\\\\\midrule\n")
    fh.write("\n".join(rows)+"\n\\bottomrule\\end{tabular}\\\\[2pt]\\raggedright\\scriptsize Ranges are across runs. 75~s of imagery is offered in each run; the payload wall time is the time to finish compressing it.\n\\end{table*}\n")
print(open('tab_mission.tex').read())
