#!/usr/bin/env python3
"""
Build the gem5 replay scenarios for one ML-DSA-44 signature.

  1. Run the signature through dilithium_py -> unmodified bridge -> unmodified Stage 8 backend
     -> register model, recording every MMIO access.
  2. Write a job table for case B (Stage 8 as driven today) and for case C (proposed chaining,
     conservative and optimistic read policies).
  3. Compile wcore_replay.c for the host with -DHOST_CHECK and require that
       case B issues exactly the recorded bus sequence (same order, same addresses), and
       case C issues exactly the number of accesses the chaining model accounts.
  4. Cross-compile static ARM binaries for gem5 (needs aarch64-linux-gnu-gcc).

    python3 gem5/gen_scenarios.py
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))

import chain_model as cm                                   # noqa: E402
import workload as wl                                      # noqa: E402
from wcore_model import WcoreModel, load_backend           # noqa: E402

LANE = {"ntt": 0, "intt": 1, "polymulacc": 2, "shake256": 3, "shake128": 4}
BUILD = HERE / "build"


def fnv(sequence):
    h = 1469598103934665603
    for kind, addr in sequence:
        h = ((h ^ kind) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
        h = ((h ^ addr) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


def header(path, jobs, plan, chain):
    lines = [f"/* generated by gen_scenarios.py: {'PROPOSED chained driver' if chain else 'Stage 8 driver as today'} */",
             f"#define MODE_CHAIN {1 if chain else 0}", f"#define N_JOBS {len(jobs)}u", "static const job_t JOBS[] = {"]
    for j, p in zip(jobs, plan):
        lines.append("  {%d, %d, %d, %d, %d, %d, %du, %du, 0x%08Xu, 0x%08Xu}," % (
            LANE[j["name"]], int(p["new_program"]), j["tx_words"], j["rx_words"], p["load_words"], p["read_words"],
            j["msg_bytes"] or 0, j["out_bytes"] or 0, j["descriptor"] & 0xFFFFFFFF, j["descriptor"] >> 32))
    lines.append("};")
    path.write_text("\n".join(lines) + "\n")


def compile_and_check(name, expected):
    src, hdr = HERE / "wcore_replay.c", BUILD / f"scenario_{name}.h"
    host = BUILD / f"check_{name}"
    subprocess.run(["gcc", "-O1", "-DHOST_CHECK", f'-DSCENARIO_HEADER="{hdr}"', "-o", str(host), str(src)], check=True)
    out = subprocess.run([str(host)], capture_output=True, text=True, check=True).stdout.split()
    got = dict(reads=int(out[1]), writes=int(out[3]), hash=out[5])
    ok = got["reads"] == expected["reads"] and got["writes"] == expected["writes"] and \
        (expected.get("hash") is None or got["hash"] == expected["hash"])
    arm = None
    cross = shutil.which("aarch64-linux-gnu-gcc")
    if cross:
        arm = BUILD / f"wcore_replay_{name}"
        subprocess.run([cross, "-O2", "-static", f'-DSCENARIO_HEADER="{hdr}"', "-o", str(arm), str(src)], check=True)
    return got, ok, arm


def main():
    BUILD.mkdir(exist_ok=True)
    model = WcoreModel(kernels=wl.FUNCTIONAL_KERNELS)
    hw = load_backend(model)
    w = wl.Workload(hw, model.jobs)
    (pk, sk), _, _ = w.keygen(bytes(range(32)))
    start = len(model.trace)
    sig, jobs, iterations = w.sign(sk, b"RSCL validation message")
    trace = model.trace[start:]
    hw.close()
    recorded = dict(reads=sum(t[0] == "R" for t in trace), writes=sum(t[0] == "W" for t in trace),
                    hash="%016x" % fnv((1 if k == "R" else 2, b + o) for k, b, o, v, c in trace))

    scenarios = {}
    stage8_plan = [dict(new_program=True, load_words=j["tx_words"], read_words=j["rx_words"]) for j in jobs]
    header(BUILD / "scenario_sign_stage8.h", jobs, stage8_plan, chain=False)
    got, ok, arm = compile_and_check("sign_stage8", recorded)
    acc = cm.account_stage8(jobs)
    scenarios["sign_stage8"] = dict(case="B stage8 actual", expected_mmio_reads=recorded["reads"],
                                    expected_mmio_writes=recorded["writes"], bus_sequence_hash=recorded["hash"],
                                    host_check_passed=ok, accounting=acc, binary="wcore_replay_sign_stage8")
    print(f"case B   recorded {recorded}  C replay {got}  identical bus sequence: {ok}")

    for tag, policy in (("sign_chain_cons", "all"), ("sign_chain_opt", "unconsumed")):
        plan = []
        acc = cm.account_chain(jobs, read_policy=policy, plan=plan)
        header(BUILD / f"scenario_{tag}.h", jobs, plan, chain=True)
        got, _, arm = compile_and_check(tag, dict(reads=0, writes=0))
        ok = got["reads"] + got["writes"] == acc["mmio_total"]
        scenarios[tag] = dict(case=f"C chain ({'conservative' if policy == 'all' else 'optimistic'}), PROPOSED",
                              expected_mmio_reads=got["reads"], expected_mmio_writes=got["writes"],
                              host_check_passed=ok, accounting=acc, binary=f"wcore_replay_{tag}")
        print(f"case C {policy:10s} model accounts {acc['mmio_total']} MMIO, C replay issues {got['reads'] + got['writes']}: {ok}")

    meta = dict(workload="ML-DSA-44 sign, message 'RSCL validation message', key from seed 00..1f",
                rejection_iterations=iterations, kernel_dispatches=len(jobs), scenarios=scenarios,
                note="Counts are from source replay and model accounting. None are AUP1 measurements.")
    (BUILD / "scenarios.json").write_text(json.dumps(meta, indent=1))
    if not all(s["host_check_passed"] for s in scenarios.values()):
        sys.exit("HOST CHECK FAILED: the C replay does not match")
    if not shutil.which("aarch64-linux-gnu-gcc"):
        print("aarch64-linux-gnu-gcc not found: ARM binaries not rebuilt (prebuilt ones may be in gem5/build)")
    print("scenarios written to", BUILD)


if __name__ == "__main__":
    main()
